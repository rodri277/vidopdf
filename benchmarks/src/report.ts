import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { passes, rawResults, resultsDir } from './harness';
import type { Measurement } from './harness';
import { round } from './stats';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');

export function readMeasurements(): Measurement[] {
  if (!existsSync(rawResults)) return [];
  return readFileSync(rawResults, 'utf8')
    .split('\n')
    .filter((line) => line.trim() !== '')
    .map((line) => JSON.parse(line) as Measurement);
}

function git(...args: string[]): string {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

export interface Environment {
  readonly date: string;
  readonly version: string;
  readonly commit: string;
  readonly machine: string;
  readonly memory: string;
  readonly node: string;
  readonly browser: string;
}

export function describeEnvironment(browser: string): Environment {
  const pkg = JSON.parse(readFileSync(join(root, 'apps/web/package.json'), 'utf8')) as {
    version: string;
  };
  return {
    date: new Date().toISOString().slice(0, 10),
    version: pkg.version,
    commit:
      git('rev-parse', '--short', 'HEAD') +
      (git('status', '--porcelain') === '' ? '' : ' plus uncommitted changes'),
    machine: `${os.cpus()[0]?.model ?? 'unknown CPU'} (${String(os.cpus().length)} cores, ${os.platform()} ${os.arch()})`,
    memory: `${String(Math.round(os.totalmem() / 1024 ** 3))} GB`,
    node: process.version,
    browser,
  };
}

function cell(measurement: Measurement | undefined): string {
  if (measurement === undefined) return 'n/a';
  const value = `${String(round(measurement.value, measurement.value < 10 ? 2 : 1))} ${measurement.unit}`;
  return measurement.budget === undefined ? value : `${value} ${passes(measurement) ? '✓' : '✗'}`;
}

/** The results as the Markdown table kept in the repository. */
export function renderMarkdown(
  measurements: readonly Measurement[],
  environment: Environment,
): string {
  const rows = new Map<string, { budget: string; byRate: Map<number, Measurement> }>();
  for (const m of measurements) {
    const key = `${m.scenario}\u0000${m.metric}`;
    const budget =
      m.budget === undefined
        ? ''
        : `${m.atLeast === true ? '≥' : '≤'} ${String(m.budget)} ${m.unit}`;
    const row = rows.get(key) ?? { budget, byRate: new Map() };
    row.byRate.set(m.cpuSlowdown, m);
    rows.set(key, row);
  }
  const lines = [
    '# Benchmark results',
    '',
    'Generated by `pnpm bench`. Do not edit by hand; rerun the suite to refresh it.',
    '',
    `- Date: ${environment.date}, version ${environment.version} (commit ${environment.commit})`,
    `- Machine: ${environment.machine}, ${environment.memory} of memory`,
    `- Browser: ${environment.browser}, Node ${environment.node}`,
    '- "4x slower" runs the same test with the page\'s main thread throttled four times, a rough stand-in for the mid-range laptop SPEC budgets refer to. The throttle does not reach the workers, so times dominated by building PDFs or pictures (which run in workers) barely change between the two columns.',
    '- The interaction rows measure from the key press to the painted result, which includes waiting for two animation frames (about 33 ms) however little work was done; the row "of which the handler and render" is the work itself.',
    '- ✓ means within the budget, ✗ means over it. Memory is the resident size of the browser renderer processes (page and workers).',
    '',
    '| Scenario | Metric | Budget | This machine | 4x slower |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const [key, row] of rows) {
    const [scenario, metric] = key.split('\u0000');
    lines.push(
      `| ${scenario ?? ''} | ${metric ?? ''} | ${row.budget} | ${cell(row.byRate.get(1))} | ${cell(row.byRate.get(4))} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}

export function writeReport(browser: string): void {
  const measurements = readMeasurements();
  const environment = describeEnvironment(browser);
  writeFileSync(
    join(resultsDir, 'latest.json'),
    `${JSON.stringify({ environment, measurements }, null, 2)}\n`,
  );
  writeFileSync(join(root, 'benchmarks/RESULTS.md'), renderMarkdown(measurements, environment));
}
