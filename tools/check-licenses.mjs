// Audits the licenses of everything Vidopdf ships to the browser and keeps THIRD_PARTY_LICENSES.md
// in sync. `node tools/check-licenses.mjs` verifies (CI); `--write` regenerates the file.
// Policy: SPEC.md "Stack tecnológico" and docs/adr/005-license-policy.md.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { init } from 'license-checker-rseidelsohn';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'THIRD_PARTY_LICENSES.md');
// The same list as data, for the Licenses page inside the app.
const dataFile = join(root, 'apps/web/src/legal/licenses.json');
// A software bill of materials (CycloneDX 1.5), served with the site and attached to releases.
const sbomFile = join(root, 'apps/web/public/sbom.cdx.json');

const ALLOWED = new Set([
  'MIT',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  'CC0-1.0',
  'OFL-1.1',
  '0BSD',
  // Permissive and OSI-approved (a notice, no misrepresentation); ADR 005. Comes with pako.
  'Zlib',
]);

/** Approved exceptions: package name -> license. Each one needs an ADR. */
const EXCEPTIONS = new Map([]);

/**
 * Pieces that ship inside pdfjs-dist under licenses of their own. Each one is served from
 * /pdfjs/ together with its notice file, and the Licenses page links every notice.
 */
const BUNDLED_WITH_PDFJS = [
  ['CMaps (Adobe)', 'BSD-3-Clause', ['/pdfjs/cmaps/LICENSE']],
  ['OpenJPEG decoder', 'BSD-2-Clause', ['/pdfjs/wasm/LICENSE_OPENJPEG']],
  ['JBIG2 decoder (PDFium)', 'BSD-3-Clause', ['/pdfjs/wasm/LICENSE_JBIG2']],
  ['qcms color management', 'MIT', ['/pdfjs/wasm/LICENSE_QCMS']],
  [
    'pdf.js wrappers of the decoders above',
    'Apache-2.0',
    [
      '/pdfjs/wasm/LICENSE_PDFJS_OPENJPEG',
      '/pdfjs/wasm/LICENSE_PDFJS_JBIG2',
      '/pdfjs/wasm/LICENSE_PDFJS_QCMS',
    ],
  ],
  ['Foxit standard fonts (PDFium)', 'BSD-3-Clause', ['/pdfjs/standard_fonts/LICENSE_FOXIT']],
  ['ICC profiles', 'CC0-1.0', ['/pdfjs/iccs/LICENSE']],
];

function scan(start) {
  return new Promise((resolve, reject) => {
    init({ start, production: true, excludePrivatePackages: true }, (error, packages) => {
      if (error) reject(error);
      else resolve(packages);
    });
  });
}

const found = {};
for (const workspace of ['apps/web', 'packages/pdf-adapters', 'packages/core']) {
  Object.assign(found, await scan(join(root, workspace)));
}

const rows = Object.entries(found)
  .map(([id, info]) => {
    const at = id.lastIndexOf('@');
    return {
      name: id.slice(0, at),
      version: id.slice(at + 1),
      license: String(info.licenses),
      file: info.licenseFile,
    };
  })
  // Workspace packages are ours; the rest are build-time type packages that never ship.
  .filter((row) => !/^(@vidopdf\/|@types\/|typescript$|csstype$)/.test(row.name))
  .sort((a, b) => a.name.localeCompare(b.name));

const violations = rows.filter((row) => {
  const exception = EXCEPTIONS.get(row.name);
  if (exception !== undefined) return exception !== row.license;
  // "A OR B" is fine if one side is allowed; "A AND B" only if every part is.
  return !row.license
    .replace(/[()]/g, '')
    .split(/ OR /)
    .some((choice) => choice.split(/ AND /).every((part) => ALLOWED.has(part.trim())));
});

function render() {
  const lines = [
    '# Third-party licenses',
    '',
    'Generated by `node tools/check-licenses.mjs --write`. Do not edit by hand.',
    'Policy: [ADR 005](docs/adr/005-license-policy.md).',
    '',
    '## npm packages shipped to the browser',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...rows.map((row) => `| ${row.name} | ${row.version} | ${row.license} |`),
    '',
    '## Bundled with pdfjs-dist (served from `/pdfjs/`, each with its notice file)',
    '',
    '| Component | License | Notice |',
    '| --- | --- | --- |',
    ...BUNDLED_WITH_PDFJS.map(
      ([name, license, notices]) => `| ${name} | ${license} | ${notices.join(', ')} |`,
    ),
    '',
    '## Full license texts',
    '',
  ];
  for (const row of rows) {
    if (!row.file) continue;
    let text = '';
    try {
      // Normalize line endings so the file is identical on every machine and in CI.
      text = readFileSync(row.file, 'utf8').replace(/\r\n?/g, '\n').trim();
    } catch {
      continue;
    }
    lines.push(`### ${row.name} ${row.version} (${row.license})`, '', '```text', text, '```', '');
  }
  return `${lines.join('\n')}\n`;
}

if (violations.length > 0) {
  for (const v of violations)
    process.stderr.write(`Disallowed license: ${v.name}@${v.version} is ${v.license}\n`);
  process.exit(1);
}

const next = render();
const data = `${JSON.stringify(
  {
    packages: rows.map(({ name, version, license }) => ({ name, version, license })),
    bundled: BUNDLED_WITH_PDFJS.map(([name, license, notices]) => ({ name, license, notices })),
  },
  null,
  2,
)}\n`;
const purl = (name, version) => `pkg:npm/${name.replace('@', '%40')}@${version}`;
const licenseOf = (license) =>
  / (OR|AND) /.test(license) ? { expression: license } : { license: { id: license } };

/** Deterministic on purpose (no timestamp, no serial number), so the CI check can compare it. */
const sbom = `${JSON.stringify(
  {
    bomFormat: 'CycloneDX',
    specVersion: '1.5',
    version: 1,
    metadata: {
      component: { type: 'application', name: 'vidopdf', licenses: [{ license: { id: 'MIT' } }] },
    },
    components: [
      ...rows.map((row) => ({
        type: 'library',
        name: row.name,
        version: row.version,
        purl: purl(row.name, row.version),
        licenses: [licenseOf(row.license)],
      })),
      ...BUNDLED_WITH_PDFJS.map(([name, license]) => ({
        type: 'data',
        name,
        licenses: [licenseOf(license)],
      })),
    ],
  },
  null,
  2,
)}\n`;

function read(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return ''; // a missing file is reported below
  }
}

if (process.argv.includes('--write')) {
  writeFileSync(outFile, next);
  mkdirSync(dirname(dataFile), { recursive: true });
  writeFileSync(dataFile, data);
  mkdirSync(dirname(sbomFile), { recursive: true });
  writeFileSync(sbomFile, sbom);
  process.stdout.write(`Wrote ${outFile} and ${dataFile} (${String(rows.length)} packages)\n`);
} else {
  const stale = [
    [outFile, next],
    [dataFile, data],
    [sbomFile, sbom],
  ].filter(([file, content]) => read(file) !== content);
  if (stale.length > 0) {
    process.stderr.write(
      `Out of date: ${stale.map(([file]) => file.replace(`${root}/`, '')).join(', ')}. Run: node tools/check-licenses.mjs --write\n`,
    );
    process.exit(1);
  }
  process.stdout.write(`Licenses OK (${String(rows.length)} packages)\n`);
}
